"""Справочник валют: ISO-код -> (название для пользователя, синонимы)."""
from __future__ import annotations

CURRENCIES: dict[str, tuple[str, tuple[str, ...]]] = {
    "RUB": ("российский рубль", ("рубль", "рубли", "рублей", "руб")),
    "USD": ("доллар США", ("доллар", "доллары", "долларов", "бакс")),
    "EUR": ("евро", ("евро",)),
    "GBP": ("фунт стерлингов", ("фунт", "фунты")),
    "JPY": ("японская иена", ("иена", "иены", "йена")),
    "CNY": ("китайский юань", ("юань", "юани")),
    "CHF": ("швейцарский франк", ("франк",)),
    "PLN": ("польский злотый", ("злотый",)),
    "CZK": ("чешская крона", ("чешская_крона",)),
    "SEK": ("шведская крона", ("шведская_крона",)),
    "NOK": ("норвежская крона", ("норвежская_крона",)),
    "TRY": ("турецкая лира", ("лира",)),
    "KRW": ("южнокорейская вона", ("вона",)),
    "AED": ("дирхам ОАЭ", ("дирхам",)),
    "ILS": ("израильский шекель", ("шекель",)),
    "INR": ("индийская рупия", ("рупия",)),
    "IDR": ("индонезийская рупия", ("индонезийская_рупия",)),
    "THB": ("тайский бат", ("бат",)),
    "PHP": ("филиппинское песо", ("песо",)),
    "RON": ("румынский лей", ("лей",)),
    "BGN": ("болгарский лев", ("лев",)),
    "HUF": ("венгерский форинт", ("форинт",)),
    "KZT": ("казахстанский тенге", ("тенге",)),
    "BYN": ("белорусский рубль", ("белорусский_рубль",)),
}

_ALIASES: dict[str, str] = {}
for _code, (_name, _synonyms) in CURRENCIES.items():
    _ALIASES[_code.lower()] = _code
    for _syn in _synonyms:
        _ALIASES[_syn] = _code


def resolve_currency(word: str) -> str | None:
    """Возвращает ISO-код по слову пользователя («Доллар», «usd») или None."""
    return _ALIASES.get(word.strip().lower().replace("ё", "е"))


def currencies_help() -> str:
    lines = [f"{code} — {name} ({', '.join(syn)})" for code, (name, syn) in CURRENCIES.items()]
    return "Доступные валюты (можно писать код или слово):\n\n" + "\n".join(lines)
